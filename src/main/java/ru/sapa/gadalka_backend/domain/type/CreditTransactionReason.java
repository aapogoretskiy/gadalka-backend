package ru.sapa.gadalka_backend.domain.type;

public enum CreditTransactionReason {
    /** Начисление за успешный платёж */
    PAYMENT,
    /** Списание при использовании функции */
    FEATURE_SPEND,
    /** Бесплатный начальный знак при регистрации */
    FREE_GRANT,
    /** Возврат кредитов при рефанде */
    REFUND,
    /** Покупка темы (колоды) карт */
    THEME_PURCHASE,
    /** Подарок от администратора через админ-панель (одиночный) */
    ADMIN_GIFT,
    /** Массовое начисление знаков через функцию рассылки */
    ADMIN_BROADCAST,
    /** Начисление за приглашение нового пользователя по реферальной ссылке */
    REFERRAL_REWARD,
    /** Компенсационный подарок при закрытии заявки обратной связи */
    SUPPORT_GIFT
}
