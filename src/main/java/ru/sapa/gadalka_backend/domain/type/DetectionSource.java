package ru.sapa.gadalka_backend.domain.type;

/**
 * Каким механизмом обнаружен чувствительный вопрос — нужно для админки,
 * чтобы отличать мгновенный keyword-матч от решения LLM и от бэкафилла истории.
 */
public enum DetectionSource {
    /** Сработал keyword-фильтр (детерминировано, без обращения к LLM) */
    KEYWORD,
    /** Сработал LLM-классификатор до генерации интерпретации (реальное время) */
    LLM_PRECHECK,
    /** Keyword и pre-check пропустили вопрос, но сгенерированный ответ LLM оказался отказом */
    LLM_REFUSAL_FALLBACK,
    /** Найдено бэкафиллом по keyword-фильтру среди уже существующих вопросов */
    BACKFILL_KEYWORD,
    /** Найдено бэкафиллом LLM-классификатором среди уже существующих вопросов */
    BACKFILL_LLM,
    /** Запись создана до появления этого поля — источник неизвестен */
    LEGACY_UNKNOWN
}
