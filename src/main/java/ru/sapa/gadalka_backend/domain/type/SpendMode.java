package ru.sapa.gadalka_backend.domain.type;

/**
 * Чем пользователь оплачивает платное действие.
 * Выбор делает сам пользователь в модалке на фронте (если доступны оба способа).
 */
public enum SpendMode {
    /** Списать знаки с баланса (старое поведение, дефолт для обратной совместимости) */
    CREDITS,
    /** Списать 1 квоту активной подписки на данную фичу */
    QUOTA
}
