-- Отметка, что пользователю уже сообщили об исчерпании Лимитов подписки.
--
-- Раньше подписка с полностью потраченными Лимитами закрывалась досрочно
-- (статус EXHAUSTED, слот «одной подписки» освобождался). Теперь оплаченный
-- период живёт до expires_at независимо от остатка Лимитов, а пользователь
-- получает сообщение и сам решает: продолжить за знаки или оформить другую
-- подписку взамен текущей.
--
-- Поле нужно от повторов: состояние «всё потрачено» наступает не один раз,
-- а при каждой следующей попытке списать Лимит. Сообщение должно уйти один
-- раз за расчётный период. При автопродлении создаётся НОВАЯ строка
-- subscriptions, где поле пустое — в новом периоде уведомим заново.
ALTER TABLE subscriptions ADD COLUMN quotas_exhausted_notified_at TIMESTAMPTZ;
