-- Фиксация цены подписки на момент оформления/последнего продления.
--
-- Юрист прямо указал (п. 6.11.3(1) пользовательского соглашения), что сумма
-- заранее данного акцепта — это цена тарифа, действующая на момент оформления
-- согласия. Чтобы при автопродлении не начать молча списывать по новой,
-- изменённой админом цене плана, фиксируем цену снапшотом на подписке и
-- переносим её из цикла в цикл (как root_payment_id и auto_renew_enabled) —
-- см. SubscriptionActivationService.
--
-- Если админ впоследствии меняет цену плана — уже действующие подписчики
-- с автопродлением продолжают платить по своей зафиксированной цене.
-- Уведомление подписчиков о самом факте изменения цены плана (вдруг подешевело
-- и человек захочет переоформиться) — отдельная задача, этим полем не покрывается.
ALTER TABLE subscriptions
    ADD COLUMN locked_price_rub INTEGER;
