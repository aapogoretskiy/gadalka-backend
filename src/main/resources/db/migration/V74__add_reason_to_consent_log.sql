-- Причина отзыва согласия на автопродление.
--
-- Отзыв бывает не только по воле пользователя: согласие гасится и когда подписка
-- закрывается досрочно (все квоты потрачены), и при отказе от подписки, и при
-- возврате денег. Для доказательной базы важно различать эти случаи — «согласие
-- отозвано» без причины в споре звучит одинаково и для действия пользователя,
-- и для действия системы.
--
-- NULL — строки GRANTED (у выдачи согласия причины нет) и исторические записи,
-- сделанные до этой миграции.
ALTER TABLE subscription_autorenew_consent_log
    ADD COLUMN reason VARCHAR(50);
