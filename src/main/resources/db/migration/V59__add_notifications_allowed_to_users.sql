-- Флаг: может ли бот проактивно писать этому пользователю в Telegram.
--
-- Проблема: Mini App можно открыть по прямой ссылке (?startapp=CODE), минуя
-- команду /start — в этом случае у пользователя создаётся профиль в БД, но
-- чата с ботом не существует, и sendMessage падает с "chat not found".
-- Это основной источник ошибок в рассылках и плановых уведомлениях.
--
-- Флаг выставляется в true:
--   - когда бот получает любое сообщение от пользователя (в т.ч. /start
--     и служебное write_access_allowed от WebApp.requestWriteAccess());
--   - при успешной отправке рассылки/уведомления (сам факт успеха доказывает,
--     что чат существует — актуально для пользователей, заведших чат ещё
--     до появления этого флага).
-- Сбрасывается в false при ошибках Telegram "chat not found" / "bot was blocked".
--
-- DEFAULT FALSE: для существующих пользователей флаг будет автоматически
-- выставлен в true при первой успешной отправке (см. BroadcastService,
-- NotificationSchedulerService) — миграция по данным не нужна.

ALTER TABLE users
    ADD COLUMN notifications_allowed BOOLEAN NOT NULL DEFAULT FALSE;
