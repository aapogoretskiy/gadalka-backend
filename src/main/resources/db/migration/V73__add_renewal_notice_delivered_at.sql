-- Право списать деньги даёт только ДОСТАВЛЕННОЕ уведомление об автопродлении.
--
-- Было: одно поле renewal_notice_sent_at, которое SubscriptionRenewalScheduler
-- проставлял всегда — в том числе когда уведомление физически не ушло (пользователь
-- заблокировал бота, забанен или удалён). Кандидаты на списание отбирались ровно
-- по «поле не NULL»
--
-- Стало: два разных факта в двух полях.
--   renewal_notice_sent_at      — последняя ПОПЫТКА отправки (диагностика, правом
--                                 на списание не является);
--   renewal_notice_delivered_at — уведомление реально доставлено. Только это поле
--                                 даёт право на списание, и только когда с момента
--                                 доставки прошло не меньше 24 часов.
--
-- Бэкфилл: подтвердить доставку задним числом нельзя, но без бэкфилла уже
-- предупреждённые подписки получили бы уведомление повторно

ALTER TABLE subscriptions
    ADD COLUMN renewal_notice_delivered_at TIMESTAMPTZ;

UPDATE subscriptions
   SET renewal_notice_delivered_at = renewal_notice_sent_at
 WHERE renewal_notice_sent_at IS NOT NULL;
